import { ENGLISH, sourceText, type Catalog } from '../locales/runtime';
const catalogs: Record<string, Catalog> = { en: ENGLISH, es: spanish, hi: hindi, pt: portuguese, de: german, fr: french, it: italian, 'zh-Hans': chinese, ro: romanian, ca: catalan, ja: japanese, nl: dutch, sv: swedish, da: danish, nb: norwegian, ko: korean, th: thai, 'zh-Hant': traditionalChinese, vi: vietnamese, id: indonesian, ms: malay, tr: turkish, ru: russian, uk: ukrainian, pl: polish, cs: czech, sk: slovak, sl: slovenian, hr: croatian, hu: hungarian, fi: finnish, el: greek, he: hebrew, ur: urdu, bn: bangla, or: odia, pa: punjabi, mr: marathi, gu: gujarati, kn: kannada, ta: tamil, te: telugu, ml: malayalam, sw: swahili, ha: hausa, yo: yoruba, ig: igbo, zu: zulu, am: amharic };
export function notificationText(text: string, locale = 'en'): string {
  const code = Object.hasOwn(catalogs, locale) ? locale : 'en';
  return sourceText(text, code, catalogs[code]);
}
