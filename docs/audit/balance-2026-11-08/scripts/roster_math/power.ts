  // greedy-by-dew order respecting level prerequisites: since perDew falls with level inside a troop, sorted order already respects prerequisites.
  const newest = Math.max(...S.map((s) => s.tier));
  let cum = 0, idx = -1;
  for (let i = 0; i < byDew.length; i++) { cum += byDew[i].dew; if (byDew[i].tier === newest && idx < 0) { idx = i; break; } }
  const cumBefore = byDew.slice(0, idx).reduce((a, s) => a + s.dew, 0);
  const touchedBefore = new Set(byDew.slice(0, idx).map((s) => s.id)).size;
  console.log(`Greedy by Provisions reaches the first tier-${newest} research at position ${idx + 1} of ${S.length}, after ${k(cumBefore)} dew spent on ${touchedBefore} older troops (${f1((cumBefore / S.reduce((a, s) => a + s.dew, 0)) * 100)}% of everything researchable at this Keep).`);
  // time-greedy: first position of oldest tier
  const tIdx = byDay.findIndex((s) => s.tier === 1);
  console.log(`Greedy by lane-time reaches the first tier-1 research at position ${tIdx + 1}; its first ${Math.min(10, byDay.length)} steps are tiers ${byDay.slice(0, 10).map((s) => s.tier).join('')}.`);
  // a bot-mix budget: research dew to bring the Keep's bot mix to caps
  const mix = botArmy(keep, 1, data);
