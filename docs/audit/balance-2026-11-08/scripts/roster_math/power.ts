// ---------------------------------------------------------------- research exchange rate + greedy
interface Step { id: string; role: string; tier: number; toLevel: number; dPh: number; dew: number; sec: number; perDew: number; perDay: number }
function stepsAt(keep: number): Step[] {
  const out: Step[] = [];
  for (const id of ids) {
    if (troopKeep(id) > keep) continue;
    const def = data.troops[id];
    const cap = Math.min(def.levels.length, troopLevelCapAt(keep, data, id));
    for (let L = 2; L <= cap; L++) {
      const a = statsAt(id, L - 1), b = statsAt(id, L);
      const dPh = (b.power - a.power) / def.housing;
      const r = def.levels[L - 1].research!;
      out.push({ id, role: entryOf[id].role, tier: entryOf[id].tier, toLevel: L, dPh, dew: r.cost.dew ?? 0, sec: r.seconds, perDew: dPh / (r.cost.dew ?? 1), perDay: dPh / (r.seconds / 86400) });
    }
  }
  return out;
}
