  for (let keep = 1; keep <= 15; keep++) {
    const mix = botArmy(keep, 1, data);
    let budget = 0;
    for (const t of Object.keys(mix)) budget += researchBetween(t, Math.max(1, Math.min(data.troops[t].levels.length, keep > 1 && troopKeep(t) <= keep - 1 ? troopLevelCapAt(keep - 1, data, t) : 1)), Math.min(data.troops[t].levels.length, troopLevelCapAt(keep, data, t))).dew;
    total += budget;
    let spent = 0;
    while (true) {
      const S = stepsAt(keep).filter((s) => s.toLevel === (done[s.id] ?? 1) + 1).sort((a, b) => b.perDew - a.perDew);
      const s = S.find((x) => spent + x.dew <= budget);
      if (!s) break;
      spent += s.dew; done[s.id] = s.toLevel; touched.add(s.id);
    }
    perKeep.push(`K${keep}: budget ${k(budget)}, touched so far ${touched.size}, levels ${Object.entries(done).map(([t, l]) => `${t.slice(0, 6)}${l}`).join(' ')}`);
  }
