  console.log(`\nKeep ${keep}: ${S.length} research steps available over ${new Set(S.map((s) => s.id)).size} troops; total ${k(S.reduce((a, s) => a + s.dew, 0))} dew, ${f1(S.reduce((a, s) => a + s.sec, 0) / 86400 / lanesAt(keep))} days on ${lanesAt(keep)} lanes.`);
