interface Row {
  id: string; name: string; role: string; tier: number; keep: number; cap: number; housing: number;
  hp: number; dps: number; power: number; ph: number; costH: number; costPerPower: number; trainSecH: number;
  res1: number; resPrev: number; days1: number; daysPrev: number; prevCap: number; dpsScale: number;
}
function statsAt(id: string, level: number) {
  const def = data.troops[id];
  const lv = def.levels[Math.min(level, def.levels.length) - 1];
  const dps = (lv.damage * data.battle.ticksPerSecond) / def.attackIntervalTicks;
  return { hp: lv.hp, dps, power: Math.sqrt(lv.hp * dps), cost: lv.cost.dew ?? 0, level: lv.level };
}
function researchBetween(id: string, from: number, to: number) {
  const def = data.troops[id];
  let dew = 0, sec = 0;
  for (const lv of def.levels) if (lv.level > from && lv.level <= to && lv.research) { dew += lv.research.cost.dew ?? 0; sec += lv.research.seconds; }
  return { dew, sec };
}
const rows: Row[] = [];
for (let keep = 1; keep <= 15; keep++) {
  for (const id of ids) {
    if (troopKeep(id) > keep) continue;
    const def = data.troops[id];
    const w = entryOf[id];
    const cap = Math.min(def.levels.length, troopLevelCapAt(keep, data, id));
    const prevKeep = keep - 1;
    const prevCap = prevKeep >= 1 && troopKeep(id) <= prevKeep ? Math.min(def.levels.length, troopLevelCapAt(prevKeep, data, id)) : 0;
    const s = statsAt(id, cap);
    const r1 = researchBetween(id, 1, cap);
    const rp = researchBetween(id, Math.max(1, prevCap), cap);
    rows.push({
      id, name: def.name, role: w.role, tier: w.tier, keep, cap, housing: def.housing,
      hp: s.hp, dps: s.dps, power: s.power, ph: s.power / def.housing, costH: s.cost / def.housing, costPerPower: s.cost / s.power,
      trainSecH: def.trainSeconds / def.housing / dojoSpeedAt(keep),
      res1: r1.dew, resPrev: prevCap ? rp.dew : r1.dew, days1: r1.sec / 86400, daysPrev: (prevCap ? rp.sec : r1.sec) / 86400, prevCap, dpsScale: w.dpsScale ?? 1,
    });
  }
}

