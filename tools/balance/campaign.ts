/**
 * Long campaigns with the model player (tools/balance/playerModel.ts): real
 * timers, earned resources, real battles and offline raids, played until Keep
 * 15 (or a day limit). Reports when each Keep was reached and how raids went
 * at each Keep, so late-game farming (the audit's F22: 97% three-star raids at
 * Keep 15) is measured, not assumed. Run: npm run balance:campaign
 */
import { defaultData } from '../../src/gameplay/sim/data';
import type { GameData } from '../../src/gameplay/sim/types';
import { activeHour, casualDays, ModelPlayer, normalDays, type ModelOptions } from './playerModel';

export interface CampaignResult {
  name: string;
  /** Day each Keep level was reached. */
  reached: Record<number, number>;
  days: number;
  /** Raids by the attacker's Keep. */
  byKeep: { keep: number; raids: number; stars: number; threeStar: number; destruction: number; opponentKeep: number; strength: number; honor: number }[];
  defenses: number;
}

export function runCampaign(name: string, opts: ModelOptions, casual: boolean, maxDays: number, data: GameData = defaultData): CampaignResult {
  const p = new ModelPlayer(data, opts);
  activeHour(p, 60, 2);
  let days = 0;
  const step = casual ? casualDays : normalDays;
  // Play in weeks until Keep 15 has been played for two weeks, or the limit.
  let topSince = -1;
  while (days < maxDays) {
    step(p, 7);
    days += 7;
    if (p.hallReachedAt[data.hall.levels.length] !== undefined && topSince < 0) topSince = days;
    if (topSince >= 0 && days - topSince >= 14) break;
  }
  const byKeep: CampaignResult['byKeep'] = [];
  for (let k = 1; k <= data.hall.levels.length; k++) {
    const rs = p.raidLog.filter((r) => r.hall === k);
    if (!rs.length) continue;
    const avg = (f: (r: (typeof rs)[number]) => number) => rs.reduce((a, r) => a + f(r), 0) / rs.length;
    byKeep.push({ keep: k, raids: rs.length, stars: avg((r) => r.stars), threeStar: avg((r) => (r.stars === 3 ? 1 : 0)), destruction: avg((r) => r.destruction), opponentKeep: avg((r) => r.opponentHall), strength: avg((r) => r.strength ?? 0), honor: avg((r) => r.trophies) });
  }
  const reached = Object.fromEntries(Object.entries(p.hallReachedAt).map(([k, v]) => [Number(k), +(v / 24).toFixed(1)]));
  return { name, reached, days, byKeep, defenses: p.defenseLog.length };
}

export function campaignMarkdown(results: CampaignResult[]): string {
  const L: string[] = ['# Campaigns (generated)', '', 'Generated by `npm run balance:campaign` (`tools/balance/campaign.ts`). Do not edit by hand.', ''];
  L.push('The model player (`tools/balance/playerModel.ts`) plays real timers, earned resources, real battles and offline raids with the simple bot attack plan (a human usually does better). Opponents are matched by honor, but never below the attacker\'s earned strength (Keep and research) minus `powerSlack`.', '');
  for (const r of results) {
    L.push(`## ${r.name}`, '');
    L.push(`Keep reached (day): ${Object.entries(r.reached).map(([k, v]) => `${k}: ${v}`).join(' · ')}. Played ${r.days} days; ${r.defenses} raids against the village.`, '');
    L.push('| Keep | Raids | Avg stars | 3★ rate | Destruction | Opponent Keep | Army strength | Honor |', '|---|---|---|---|---|---|---|---|');
    for (const k of r.byKeep) L.push(`| ${k.keep} | ${k.raids} | ${k.stars.toFixed(2)} | ${Math.round(k.threeStar * 100)}% | ${k.destruction.toFixed(0)}% | ${k.opponentKeep.toFixed(1)} | ${k.strength.toFixed(2)} | ${Math.round(k.honor)} |`);
    L.push('');
  }
  return L.join('\n') + '\n';
}
