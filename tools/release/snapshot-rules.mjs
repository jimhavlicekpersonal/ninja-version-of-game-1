#!/usr/bin/env node
/**
 * Snapshot a released version of the battle rules for the server (roadmap
 * step 73). The server keeps the last 2-3 rule versions loaded, so a game
 * that has not updated yet is still re-simulated with the rules it played
 * with. This copies `src/gameplay/sim` and `src/gameplay/data` exactly as they
 * were at a git ref into `server/rules/v<SIM_RULES>/`, writes the entry point
 * the server loads (`index.ts`) and a checksum manifest
 * (`tests/backend/server/rule-versions.test.ts` fails if anyone edits a
 * snapshot by hand). The live code in src/gameplay/sim stays the only one
 * people change.
 *
 *   node tools/release/snapshot-rules.mjs [--ref <git ref>]   (default HEAD)
 *
 * Run it when a release bumps SIM_RULES, with the ref of the last release
 * under the old rules; then add the version to server/rules/index.ts.
 * Plain Node and git: works on Windows too.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const args = process.argv.slice(2);
const refAt = args.indexOf('--ref');
const ref = refAt >= 0 ? args[refAt + 1] : 'HEAD';
const git = (...a) => execFileSync('git', a, { cwd: ROOT, maxBuffer: 64 * 1024 * 1024 });

const sha = git('rev-parse', `${ref}^{commit}`).toString().trim();
const battle = git('show', `${sha}:src/gameplay/sim/battle/battle.ts`).toString();
const m = /export const SIM_RULES = (\d+);/.exec(battle);
if (!m) throw new Error(`No SIM_RULES in ${ref}`);
const rules = Number(m[1]);
const out = join(ROOT, 'server', 'rules', `v${rules}`);
rmSync(out, { recursive: true, force: true });

const files = git('ls-tree', '-r', '--name-only', sha, '--', 'src/gameplay/sim', 'src/gameplay/data')
  .toString()
  .split('\n')
  .filter((f) => f && !f.endsWith('.test.ts'));
const manifest = {};
const put = (rel, buf) => {
  const p = join(out, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, buf);
  manifest[rel.split('\\').join('/')] = createHash('sha256').update(buf).digest('hex');
};
for (const f of files) put(relative('src/gameplay', f), git('show', `${sha}:${f}`));

put(
  'index.ts',
  Buffer.from(`/**
 * GENERATED by tools/release/snapshot-rules.mjs from ${sha}: battle rules ${rules}
 * as released. Never edit by hand (the checksums in MANIFEST.json are tested);
 * change the live rules in src/gameplay/sim instead.
 */
import { runBattle, SIM_RULES } from './sim/battle/battle';
import type { BattleSetup, Deployment } from './sim/battle/types';
import { defaultData } from './sim/data';

export const RULES: number = SIM_RULES;
export const SOURCE = '${sha}';
export const data = defaultData;

/** One battle exactly as this version ran it, with what the server records from it. */
export function resim(job: { setup: unknown; deployments: unknown[]; endTick?: number }) {
  const out = runBattle(job.setup as BattleSetup, job.deployments as Deployment[], defaultData, job.endTick);
  const damage: Record<string, number> = {};
  for (const b of out.sim.buildings) {
    const lost = b.destroyed ? b.maxHp : b.maxHp - b.hp;
    if (lost > 0) damage[b.id] = lost;
  }
  return { result: out.result, fallen: out.sim.buildings.filter((b) => b.destroyed).map((b) => ({ id: b.id, loot: { ...b.loot } })), damage };
}
`),
);
writeFileSync(join(out, 'MANIFEST.json'), JSON.stringify({ rules, source: sha, files: manifest }, null, 1) + '\n');
console.log(`server/rules/v${rules}: ${Object.keys(manifest).length} files from ${sha.slice(0, 10)}`);
