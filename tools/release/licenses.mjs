// P7-05 (PUB-08): writes public/licenses.html, the third-party licence notices that ship with the game: every runtime
// dependency in package.json (its licence file from node_modules, in full) and the two bundled fonts (SIL OFL 1.1).
// Run: node tools/release/licenses.mjs        (writes the page)
//      node tools/release/licenses.mjs --check (exit 1 when the committed page is stale)
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** Fonts in src/presentation/ui/fonts (both SIL OFL 1.1). */
export const FONTS = [
  { name: 'M PLUS 1', file: 'mplus1-latin-var.woff2', copyright: 'Copyright 2016 The M+ FONTS Project Authors (https://github.com/coz-m/MPLUS_FONTS)' },
  { name: 'Dela Gothic One', file: 'dela-gothic-one-latin-400.woff2', copyright: 'Copyright 2020 The Dela Gothic Project Authors (https://github.com/syakuzen/DelaGothic)' },
];

function licenceText(name) {
  const dir = join(ROOT, 'node_modules', name);
  const file = readdirSync(dir).find((f) => /^licen[cs]e(\.md|\.txt)?$/i.test(f));
  if (!file) throw new Error(`${name}: no licence file in node_modules`);
  return readFileSync(join(dir, file), 'utf8').replace(/\r\n?/g, '\n').trim();
}

export function licencesHtml() {
  const deps = Object.keys(pkg.dependencies).sort();
  const parts = deps.map((name) => {
    const p = JSON.parse(readFileSync(join(ROOT, 'node_modules', name, 'package.json'), 'utf8'));
    return `<section id="${esc(name)}"><h2>${esc(name)} ${esc(p.version)}</h2><p class="muted">${esc(p.license ?? '')}${p.homepage ? ` · ${esc(p.homepage)}` : ''}</p><pre>${esc(licenceText(name))}</pre></section>`;
  });
  const ofl = readFileSync(join(ROOT, 'tools/release/OFL-1.1.txt'), 'utf8').trim();
  const fonts = FONTS.map((f) => `<section id="font-${esc(f.file)}"><h2>${esc(f.name)} (font)</h2><p class="muted">SIL Open Font License 1.1 · ${esc(f.copyright)}</p></section>`);
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Kagemura: third-party licences</title>
<style>body{font:16px/1.5 system-ui,sans-serif;max-width:760px;margin:0 auto;padding:16px;background:#f7f0e1;color:#26303d}pre{white-space:pre-wrap;font-size:13px;background:#fffaf0;padding:10px;border-radius:8px}.muted{color:#5b6472}h2{font-size:18px;margin:24px 0 4px}</style>
</head>
<body>
<h1>Third-party licences</h1>
<p>Kagemura: Ninja Clans includes the following open-source software and fonts. Generated by <code>tools/release/licenses.mjs</code> from the shipped dependencies; do not edit by hand.</p>
${parts.join('\n')}
${fonts.join('\n')}
<section id="ofl"><h2>SIL Open Font License 1.1</h2><pre>${esc(ofl)}</pre></section>
<p><a href="./support.html">Back to support</a></p>
</body>
</html>
`;
}

if (process.argv[1] && process.argv[1].endsWith('licenses.mjs')) {
  const html = licencesHtml();
  const out = join(ROOT, 'public/licenses.html');
  if (process.argv.includes('--check')) {
    const cur = existsSync(out) ? readFileSync(out, 'utf8') : '';
    if (cur !== html) {
      console.error('public/licenses.html is stale: run node tools/release/licenses.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(out, html);
    console.log(`wrote public/licenses.html (${Object.keys(pkg.dependencies).length} packages, ${FONTS.length} fonts)`);
  }
}
