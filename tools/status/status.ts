/**
 * docs/STATUS.md, generated from the code (state-of-the-game report, section 5 step 10, quality 9 and 11):
 * the numbers every brief used to repeat by hand and that went stale (protocol, battle rules, save format,
 * migrations, roster, languages). `npm run status` rewrites it; `tests/architecture/status.test.ts` fails when
 * it is out of date. Briefs point here instead of quoting numbers.
 */
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { PROTOCOL_VERSION } from '../../src/backend/net/protocol';
import { SIM_RULES, SIM_RULES_COMPATIBLE } from '../../src/gameplay/sim/battle/battle';
import { defaultData } from '../../src/gameplay/sim/data';
import { SAVE_VERSION } from '../../src/gameplay/sim/save';
import { MIN_PROTOCOL } from '../../server/core/identity';

const ROOT = process.cwd();

function countFiles(dir: string, test: (name: string) => boolean): number {
  let n = 0;
  for (const e of readdirSync(join(ROOT, dir), { withFileTypes: true })) {
    if (e.isDirectory()) n += countFiles(join(dir, e.name), test);
    else if (test(e.name)) n++;
  }
  return n;
}

export function statusMarkdown(): string {
  const migrations = readdirSync(join(ROOT, 'server/migrations')).filter((f) => /^\d{4}_.*\.sql$/.test(f)).sort();
  const archived = readdirSync(join(ROOT, 'server/rules')).filter((f) => /^v\d+$/.test(f)).map((f) => Number(f.slice(1))).sort((a, b) => b - a);
  const progression = JSON.parse(readFileSync(join(ROOT, 'src/gameplay/data/progression.json'), 'utf8')) as { buildingCatalog?: { live?: boolean }[] };
  const catalog = progression.buildingCatalog ?? [];
  const roster = JSON.parse(readFileSync(join(ROOT, 'src/gameplay/data/roster.json'), 'utf8')) as { warriors: { liveTroop?: string }[]; heroes: unknown[] };
  const languages = (JSON.parse(readFileSync(join(ROOT, 'locales/languages.json'), 'utf8')) as { languages: unknown[] }).languages;
  const uiKeys = Object.keys(JSON.parse(readFileSync(join(ROOT, 'locales/en/ui.json'), 'utf8'))).length;
  const dataKeys = Object.keys(JSON.parse(readFileSync(join(ROOT, 'locales/en/data.json'), 'utf8'))).length;
  const products = Object.keys(defaultData.store.storeProductIds ?? {}).length;
  const heroes = Object.keys(defaultData.battle.heroes ?? {});
  const rows: [string, string][] = [
    ['Protocol (`PROTOCOL_VERSION`)', `${PROTOCOL_VERSION} (servers accept from ${MIN_PROTOCOL})`],
    ['Battle rules (`SIM_RULES`)', `${SIM_RULES}${SIM_RULES_COMPATIBLE.length ? ` (also replays ${SIM_RULES_COMPATIBLE.join(', ')})` : ''}`],
    ['Archived battle rules on the server', archived.length ? archived.map((v) => `v${v}`).join(', ') : 'none'],
    ['Save format (`SAVE_VERSION`)', String(SAVE_VERSION)],
    ['Database migrations', `${migrations.length} (latest \`${migrations[migrations.length - 1]}\`)`],
    ['Warriors live', `${roster.warriors.filter((w) => w.liveTroop).length} of ${roster.warriors.length}`],
    ['Heroes live', `${heroes.length} of ${roster.heroes.length}${heroes.length ? ` (${heroes.join(', ')})` : ''}`],
    ['Buildings in the catalog', `${catalog.length} (${catalog.filter((b) => b.live).length} live)`],
    ['Keep levels', String(defaultData.hall.levels.length)],
    ['Store products', String(products)],
    ['Languages', `${languages.length} (\`locales/languages.json\`)`],
    ['Interface strings keyed', `${uiKeys} (\`locales/en/ui.json\`)`],
    ['Game data strings', `${dataKeys} (\`locales/en/data.json\`)`],
    ['Test files', String(countFiles('tests', (n) => /\.test\.ts$/.test(n)))],
  ];
  return [
    '# Status (generated)',
    '',
    'Generated by `npm run status` from the code; do not edit by hand. `tests/architecture/status.test.ts` fails when it is out of date. Briefs point here instead of repeating these numbers.',
    '',
    '| What | Now |',
    '|---|---|',
    ...rows.map(([k, v]) => `| ${k} | ${v} |`),
    '',
  ].join('\n');
}
